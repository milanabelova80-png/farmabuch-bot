async def init_db():
    db_dir = os.path.dirname(DB_NAME)
    if db_dir:
        os.makedirs(db_dir, exist_ok=True)
    async with aiosqlite.connect(DB_NAME) as db:
        await db.execute("""
            CREATE TABLE IF NOT EXISTS progress (
                user_id INTEGER,
                test_key TEXT,
                score_percent INTEGER,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY (user_id, test_key)
            )
        """)
        await db.execute("""
            CREATE TABLE IF NOT EXISTS custom_conspects (
                module_id INTEGER PRIMARY KEY,
                content TEXT,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        await db.execute("""
            CREATE TABLE IF NOT EXISTS user_settings (
                user_id INTEGER PRIMARY KEY,
                selected_module INTEGER
            )
        """)
        await db.commit()


async def save_user_selected_module(user_id: int, module_id: Optional[int]):
    async with aiosqlite.connect(DB_NAME) as db:
        await db.execute(
            """
            INSERT INTO user_settings (user_id, selected_module)
            VALUES (?, ?)
            ON CONFLICT(user_id)
            DO UPDATE SET selected_module = excluded.selected_module
            """,
            (user_id, module_id),
        )
        await db.commit()


async def get_user_selected_module(user_id: int) -> Optional[int]:
    async with aiosqlite.connect(DB_NAME) as db:
        async with db.execute(
            "SELECT selected_module FROM user_settings WHERE user_id = ?",
            (user_id,),
        ) as cursor:
            row = await cursor.fetchone()
            return row[0] if row and row[0] is not None else None


async def save_user_score(user_id: int, test_key: str, percent: int):
    async with aiosqlite.connect(DB_NAME) as db:
        await db.execute(
            """
            INSERT INTO progress (user_id, test_key, score_percent)
            VALUES (?, ?, ?)
            ON CONFLICT(user_id, test_key) 
            DO UPDATE SET score_percent = excluded.score_percent, updated_at = CURRENT_TIMESTAMP
        """,
            (user_id, test_key, percent),
        )
        await db.commit()


async def get_user_progress(user_id: int) -> Dict[str, int]:
    async with aiosqlite.connect(DB_NAME) as db:
        async with db.execute(
            "SELECT test_key, score_percent FROM progress WHERE user_id = ?",
            (user_id,),
        ) as cursor:
            rows = await cursor.fetchall()
            return {row[0]: row[1] for row in rows}


async def save_custom_conspect(module_id: int, content: str):
    async with aiosqlite.connect(DB_NAME) as db:
        await db.execute(
            """
            INSERT INTO custom_conspects (module_id, content)
            VALUES (?, ?)
            ON CONFLICT(module_id)
            DO UPDATE SET content = excluded.content, updated_at = CURRENT_TIMESTAMP
        """,
            (module_id, content),
        )
        await db.commit()


async def get_custom_conspect(module_id: int) -> Optional[str]:
    async with aiosqlite.connect(DB_NAME) as db:
        async with db.execute(
            "SELECT content FROM custom_conspects WHERE module_id = ?",
            (module_id,),
        ) as cursor:
            row = await cursor.fetchone()
            return row[0] if row else None


