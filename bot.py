async def render_progress(target_message: types.Message, user_id: int, has_selected_mod: bool = False):
    stats = await get_user_progress(user_id)
    kb = get_topic_actions_keyboard() if has_selected_mod else get_modules_reply_keyboard()

    if not stats:
        await target_message.answer(
            "📊 <b>Журнал успеваемости пока пуст.</b>\n\n"
            "Ты еще не завершил ни одного теста. Выбирай любой модуль на клавиатуре и погнали!",
            parse_mode=ParseMode.HTML,
            reply_markup=kb,
        )
        return

    report = "📊 <b>ТВОЙ ПРОГРЕСС В FARMABUCH:</b>\n\n"
    low_modules = []

    for key, val in stats.items():
        icon = "🟢" if val >= 70 else "🔴"

        if key.startswith("mod_"):
            m_num = int(key.split("_")[1])
            title = f"Модуль {m_num} (Тест)"
            if val < 70:
                low_modules.append(f"Модуль {m_num}")
        elif key.startswith("self_"):
            m_num = int(key.split("_")[1])
            title = f"Модуль {m_num} (Самопроверка)"
            if val < 70:
                low_modules.append(f"Модуль {m_num}")
        elif key == "mid_1":
            title = "Итоговая работа 1 (Мод. 1-8)"
        elif key == "mid_2":
            title = "Итоговая работа 2 (Мод. 9-16)"
        elif key == "final_exam":
            title = "🎓 ЭКЗАМЕН (50 вопр.)"
        else:
            title = key

        report += f"{icon} <b>{title}:</b> {val}%\n"

    if low_modules:
        report += "\n⚠️ <b>РЕКОМЕНДАЦИЯ FARMABUCH:</b>\n"
        report += "Обрати внимание на темы ниже 70%. Давай разберем их без зубрежки:\n"
        for lm in sorted(set(low_modules)):
            report += f"• <i>{lm}</i>\n"
    else:
        report += "\n🎉 <b>Красавчик!</b> Все сданные темы выше 70%."

    await target_message.answer(
        report,
        parse_mode=ParseMode.HTML,
        reply_markup=kb,
    )


# ================= ДВИЖОК ИИ FARMABUCH =================
async def ask_farmabuch_ai(
    message: types.Message,
    state: FSMContext,
    user_text: str,
    mode: str = "explain",
):
    await message.bot.send_chat_action(chat_id=message.chat.id, action="typing")

    data = await state.get_data()
    history = data.get("ai_history", [])
    sel_mod = await resolve_selected_module(message.from_user.id, state)
    kb = get_topic_actions_keyboard() if sel_mod else get_modules_reply_keyboard()

    system_prompt = (
        FARMABUCH_CONSPECT_PROMPT
        if mode == "conspect"
        else FARMABUCH_EXPLAIN_PROMPT
    )

    messages_payload = [{"role": "system", "content": system_prompt}]
    messages_payload.extend(history[-6:])
    messages_payload.append({"role": "user", "content": user_text})

    try:
        response = await ai_client.chat.completions.create(
            model=AI_MODEL,
            messages=messages_payload,
            temperature=0.35,
            max_tokens=1800,
        )

        ai_answer = response.choices[0].message.content

        history.append({"role": "user", "content": user_text})
        history.append({"role": "assistant", "content": ai_answer})
        await state.update_data(ai_history=history)

        try:
            if len(ai_answer) > 4000:
                for x in range(0, len(ai_answer), 4000):
                    await message.answer(
                        ai_answer[x : x + 4000],
                        parse_mode=ParseMode.HTML,
                        reply_markup=kb,
                    )
            else:
                await message.answer(
                    ai_answer,
                    parse_mode=ParseMode.HTML,
                    reply_markup=kb,
                )
        except Exception:
            await message.answer(ai_answer, reply_markup=kb)

    except Exception as e:
        logger.error(f"Ошибка ИИ: {e}")
        await message.answer(
            "⚠️ Произошла ошибка связи с сервером ИИ. Попробуй отправить запрос еще раз!"
        )


