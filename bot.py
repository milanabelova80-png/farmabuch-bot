# ================= ДВИЖОК ТЕСТОВ =================
async def init_quiz(
    target_message: types.Message,
    state: FSMContext,
    questions: list,
    title: str,
    progress_key: str,
):
    sel_mod = await resolve_selected_module(target_message.from_user.id, state)

    await state.set_state(StudyFlow.testing)
    await state.update_data(
        questions=questions,
        idx=0,
        score=0,
        title=title,
        key=progress_key,
        total=len(questions),
        selected_module=sel_mod,
    )

    q_data = questions[0]
    builder = InlineKeyboardBuilder()
    for i, opt in enumerate(q_data["options"]):
        builder.button(text=opt, callback_data=f"quiz_opt_{i}")
    builder.adjust(1)

    text = (
        f"🎯 <b>{title}</b>\n"
        f"Вопрос 1 из {len(questions)}:\n\n"
        f"<b>{q_data['q']}</b>"
    )
    await target_message.answer(
        text, reply_markup=builder.as_markup(), parse_mode=ParseMode.HTML
    )


@dp.callback_query(StudyFlow.testing, F.data.startswith("quiz_opt_"))
async def process_quiz_answer(callback: types.CallbackQuery, state: FSMContext):
    await callback.answer()
    try:
        await callback.message.edit_reply_markup(reply_markup=None)
    except Exception:
        pass

    chosen_idx = int(callback.data.split("_")[2])
    data = await state.get_data()

    idx = data["idx"]
    questions = data["questions"]
    curr_q = questions[idx]
    score = data["score"]
    total = data["total"]

    if chosen_idx == curr_q["correct"]:
        score += 1
        feedback = "✅ <b>Верно! Отличный ответ.</b>"
    else:
        right_opt = curr_q["options"][curr_q["correct"]]
        feedback = (
            f"❌ <b>Неверно!</b>\n"
            f"Правильный ответ: <b>{right_opt}</b>\n"
            f"💡 <i>Разбор FarmaBuch:</i> {curr_q['explanation']}"
        )

    await callback.message.answer(feedback, parse_mode=ParseMode.HTML)

    idx += 1
    if idx < total:
        await state.update_data(idx=idx, score=score)
        next_q = questions[idx]
        builder = InlineKeyboardBuilder()
        for i, opt in enumerate(next_q["options"]):
            builder.button(text=opt, callback_data=f"quiz_opt_{i}")
        builder.adjust(1)

        next_text = (
            f"🎯 <b>{data['title']}</b>\n"
            f"Вопрос {idx + 1} из {total}:\n\n"
            f"<b>{next_q['q']}</b>"
        )
        await callback.message.answer(
            next_text,
            reply_markup=builder.as_markup(),
            parse_mode=ParseMode.HTML,
        )
    else:
        percent = int((score / total) * 100)
        user_id = callback.from_user.id
        await save_user_score(user_id, data["key"], percent)

        result = (
            f"🏁 <b>Тестирование завершено!</b>\n\n"
            f"Срез знаний: <b>{data['title']}</b>\n"
            f"Итог: <b>{score} из {total}</b> ({percent}%)\n\n"
        )
        if percent < 70:
            result += "⚠️ <b>Внимание:</b> Результат ниже порога (70%). Советую повторить конспект и попробовать снова!"
        else:
            result += "🎉 <b>Блестяще!</b> Тема отлично усвоена."

        await state.set_state(None)
        sel_mod = data.get("selected_module")
        kb = get_topic_actions_keyboard() if sel_mod else get_modules_reply_keyboard()
        await callback.message.answer(
            result,
            parse_mode=ParseMode.HTML,
            reply_markup=kb,
        )
        await callback.message.answer(
            "Хочешь выбрать другую тему из 16 модулей?",
            reply_markup=get_back_to_topics_inline(),
        )


