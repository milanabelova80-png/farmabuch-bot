@dp.message(StudyFlow.self_checking)
async def process_self_answer(message: types.Message, state: FSMContext):
    if not message.text:
        await message.answer("⚠️ Пожалуйста, введи ответ текстом:")
        return

    if await check_if_module_button_pressed(message, state):
        return

    user_text = message.text.lower()
    data = await state.get_data()

    idx = data["idx"]
    questions = data["questions"]
    curr_q = questions[idx]
    score = data["score"]
    total = data["total"]

    matched = [kw for kw in curr_q["keywords"] if kw in user_text]
    missing = [kw for kw in curr_q["keywords"] if kw not in user_text]

    if len(matched) >= len(curr_q["keywords"]) * 0.7:
        score += 1.0
        await message.answer(
            "🟢 <b>Ответ полный и абсолютно верный! Красота!</b>",
            parse_mode=ParseMode.HTML,
        )
    elif len(matched) > 0:
        score += 0.5
        recom = ", ".join(missing)
        await message.answer(
            f"🟡 <b>Ответ частично верный.</b>\n\n"
            f"💡 <b>Стоит добавить ключевые корни:</b> <code>{recom}</code>\n\n"
            f"📖 <b>Эталон FarmaBuch:</b> {curr_q['ideal']}",
            parse_mode=ParseMode.HTML,
        )
    else:
        await message.answer(
            f"🔴 <b>В ответе не хватило ключевых медицинских понятий.</b>\n\n"
            f"📖 <b>Эталон FarmaBuch:</b> {curr_q['ideal']}",
            parse_mode=ParseMode.HTML,
        )

    idx += 1
    if idx < total:
        await state.update_data(idx=idx, score=score)
        await message.answer(
            f"Вопрос {idx + 1} из {total}:\n\n"
            f"<b>{questions[idx]['q']}</b>\n\n"
            f"💬 <i>Напиши твой ответ текстом:</i>",
            parse_mode=ParseMode.HTML,
        )
    else:
        percent = int((score / total) * 100)
        user_id = message.from_user.id
        await save_user_score(user_id, f"self_{data['mod_id']}", percent)

        await state.set_state(None)
        await message.answer(
            f"🏁 <b>Самопроверка окончена!</b>\n"
            f"Итоговая полнота: <b>{score}/{total}</b> ({percent}%)\n\n"
            f"Результат сохранен в твоем журнале прогресса.",
            parse_mode=ParseMode.HTML,
            reply_markup=get_topic_actions_keyboard(),
        )
        await message.answer(
            "Хочешь перейти к другой теме?",
            reply_markup=get_back_to_topics_inline(),
        )


