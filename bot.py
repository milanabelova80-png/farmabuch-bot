async def resolve_selected_module(user_id: int, state: FSMContext) -> Optional[int]:
    """Возвращает точно выбранный пользователем модуль (из памяти или БД)."""
    data = await state.get_data()
    mod_id = data.get("selected_module")
    if mod_id in MODULES:
        return mod_id
    db_mod = await get_user_selected_module(user_id)
    if db_mod in MODULES:
        await state.update_data(selected_module=db_mod)
        return db_mod
    return None


def extract_module_id_from_text(text: str) -> Optional[int]:
    """Точно определяет номер модуля (1..16) по тексту кнопки (от 16 к 1, без путаницы 1 и 10-16)."""
    if not text:
        return None
    cleaned = text.strip()
    # Сначала проверяем от 16 до 1 по полному тексту или префиксу
    for mod_id in range(16, 0, -1):
        mod_title = MODULES[mod_id]
        if cleaned == mod_title or cleaned.startswith(mod_title[:25]):
            return mod_id
    # Дополнительно проверяем регулярным выражением номер в начале кнопки
    match = re.match(r"^[^\d\w]*(\d{1,2})\.\s+", cleaned)
    if match:
        num = int(match.group(1))
        if 1 <= num <= 16:
            return num
    return None


